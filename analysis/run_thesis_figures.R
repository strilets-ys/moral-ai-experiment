# =============================================================================
# Figure 6: Persuasion Awareness & Self-Reported Change
# =============================================================================

debrief_data <- data %>%
  group_by(condition_clean) %>%
  summarise(
    n = n(),
    noticed_n   = sum(debrief_noticed_persuasion == TRUE, na.rm = TRUE),
    changed_n   = sum(debrief_changed_mind == TRUE, na.rm = TRUE),
    noticed_pct = noticed_n / n * 100,
    changed_pct = changed_n / n * 100,
    .groups = "drop"
  )

debrief_long <- debrief_data %>%
  dplyr::select(condition_clean, noticed_pct, changed_pct) %>%
  pivot_longer(cols = c(noticed_pct, changed_pct),
               names_to = "measure", values_to = "pct") %>%
  mutate(measure = recode(measure,
    "noticed_pct" = "Noticed persuasion",
    "changed_pct" = "Self-reported change"
  ))

p6 <- ggplot(debrief_long,
             aes(x = condition_clean, y = pct, fill = measure)) +
  geom_col(position = position_dodge(width = 0.7), width = 0.6) +
  geom_text(aes(label = sprintf("%.0f%%", pct)),
            position = position_dodge(width = 0.7),
            vjust = -0.4, size = 2.8, color = "gray20") +
  scale_fill_manual(
    values = c("Noticed persuasion"   = col_sienna,
               "Self-reported change" = col_sage),
    name = NULL
  ) +
  scale_y_continuous(labels = function(x) paste0(x, "%"),
                     limits = c(0, 115),
                     expand = expansion(mult = c(0, 0))) +
  labs(title = "Persuasion Awareness and Self-Reported Mind Change",
       subtitle = sprintf("Overall: %.0f%% noticed persuasion, %.0f%% reported changing mind",
                          sum(data$debrief_noticed_persuasion == TRUE) / nrow(data) * 100,
                          sum(data$debrief_changed_mind == TRUE) / nrow(data) * 100),
       x = NULL, y = "Percentage") +
  theme_thesis() +
  theme(axis.text.x = element_text(size = rel(0.85)))

save_thesis_fig("fig_06_debrief.pdf", p6, width = 6.5, height = 4.5)

