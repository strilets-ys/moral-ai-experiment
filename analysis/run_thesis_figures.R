# --- Setup ---
source("00_setup.R")
source("00_theme.R")
library(kableExtra)

# --- Data Preparation ---
data <- data %>%
  mutate(
    condition_clean = recode(condition, !!!condition_labels),
    condition_clean = factor(condition_clean, levels = condition_order)
  )

data_long <- data_long %>%
  mutate(
    condition_clean = recode(condition, !!!condition_labels),
    condition_clean = factor(condition_clean, levels = condition_order)
  )

data_chat_analysis <- data_chat_analysis %>%
  mutate(
    condition_clean = recode(condition, !!!condition_labels),
    condition_clean = factor(condition_clean, levels = condition_order),
    stance_clean = recode(stance_mode, !!!stance_labels),
    outcome = factor(outcome, levels = outcome_levels)
  )

message(sprintf("Data ready: %d participants, %d total obs, %d chat obs",
                nrow(data), nrow(data_long), nrow(data_chat_analysis)))

# Descriptive tables are generated by run_thesis_tables.R

# =============================================================================
# Figure 1: Overall Persuasion Outcomes
# =============================================================================

outcome_summary <- data_chat_analysis %>%
  count(outcome) %>%
  mutate(
    pct = n / sum(n) * 100,
    outcome = factor(outcome, levels = outcome_levels)
  ) %>%
  arrange(outcome)

p1 <- ggplot(outcome_summary, aes(x = "", y = pct, fill = outcome)) +
  geom_col(width = 0.7) +
  geom_text(aes(label = sprintf("%.0f%% (n=%d)", pct, n)),
            position = position_stack(vjust = 0.5),
            size = 3.5, color = "white", fontface = "bold") +
  scale_fill_manual(values = palette_outcomes, name = "Outcome") +
  scale_y_continuous(labels = function(x) paste0(x, "%"),
                     expand = expansion(mult = c(0, 0.02))) +
  labs(title = "Overall Persuasion Outcomes",
       subtitle = sprintf("All discussed dilemmas (N = %d observations)",
                          sum(outcome_summary$n)),
       x = NULL, y = "Percentage") +
  coord_flip() +
  theme_thesis() +
  theme(axis.text.y = element_blank(),
        axis.ticks.y = element_blank(),
        panel.grid.major.y = element_blank())

save_thesis_fig("fig_01_outcomes_overall.pdf", p1, width = 6.5, height = 2.8)

# =============================================================================
# Figure 2: Distribution of Rating Changes
# =============================================================================

change_stats <- data_long %>%
  summarise(m = round(mean(rating_change, na.rm = TRUE), 2),
            sd = round(sd(rating_change, na.rm = TRUE), 2),
            md = median(rating_change, na.rm = TRUE))

p2 <- ggplot(data_long, aes(x = rating_change)) +
  geom_histogram(binwidth = 1, fill = col_taupe, color = "white",
                 boundary = -0.5) +
  geom_vline(xintercept = change_stats$m, linetype = "dashed",
             color = tu_red, linewidth = 0.8) +
  annotate("text", x = change_stats$m + 0.3, y = Inf,
           label = sprintf("M = %.2f", change_stats$m),
           hjust = 0, vjust = 1.5, size = 3.2, color = tu_red) +
  scale_x_continuous(breaks = -6:6) +
  scale_y_continuous(expand = expansion(mult = c(0, 0.08))) +
  labs(title = "Distribution of Rating Changes",
       subtitle = sprintf("All dilemmas (N = %d); SD = %.2f",
                          nrow(data_long), change_stats$sd),
       x = "Rating Change (Post \u2013 Pre)",
       y = "Count") +
  theme_thesis()

save_thesis_fig("fig_02_change_distribution.pdf", p2, width = 6.5, height = 4)

# =============================================================================
# Figure 3: Outcomes by Experimental Condition
# =============================================================================

cond_outcomes <- data_chat_analysis %>%
  count(condition_clean, outcome) %>%
  group_by(condition_clean) %>%
  mutate(pct = n / sum(n) * 100,
         total_n = sum(n)) %>%
  ungroup() %>%
  mutate(outcome = factor(outcome, levels = outcome_levels))

n_labels <- cond_outcomes %>%
  distinct(condition_clean, total_n)

p3 <- ggplot(cond_outcomes,
             aes(x = condition_clean, y = pct, fill = outcome)) +
  geom_col(width = 0.7) +
  geom_text(aes(label = ifelse(pct >= 8, sprintf("%.0f%%", pct), "")),
            position = position_stack(vjust = 0.5),
            size = 3, color = "white", fontface = "bold") +
  geom_text(data = n_labels,
            aes(x = condition_clean, y = 102,
                label = sprintf("n=%d", total_n)),
            inherit.aes = FALSE, size = 2.8, color = "gray40") +
  scale_fill_manual(values = palette_outcomes, name = "Outcome") +
  scale_y_continuous(labels = function(x) paste0(x, "%"),
                     expand = expansion(mult = c(0, 0.05))) +
  labs(title = "Persuasion Outcomes by Condition",
       x = NULL, y = "Percentage") +
  theme_thesis() +
  theme(axis.text.x = element_text(size = rel(0.85)))

save_thesis_fig("fig_03_outcomes_by_condition.pdf", p3, width = 6.5, height = 4.5)

# =============================================================================
# Figure 4: Outcomes by AI Stance
# =============================================================================

stance_outcomes <- data_chat_analysis %>%
  filter(!is.na(stance_clean)) %>%
  count(stance_clean, outcome) %>%
  group_by(stance_clean) %>%
  mutate(pct = n / sum(n) * 100,
         total_n = sum(n)) %>%
  ungroup() %>%
  mutate(outcome = factor(outcome, levels = outcome_levels))

n_labels_s <- stance_outcomes %>% distinct(stance_clean, total_n)

p4 <- ggplot(stance_outcomes,
             aes(x = stance_clean, y = pct, fill = outcome)) +
  geom_col(width = 0.6) +
  geom_text(aes(label = ifelse(pct >= 8, sprintf("%.0f%%", pct), "")),
            position = position_stack(vjust = 0.5),
            size = 3.2, color = "white", fontface = "bold") +
  geom_text(data = n_labels_s,
            aes(x = stance_clean, y = 102,
                label = sprintf("n=%d", total_n)),
            inherit.aes = FALSE, size = 2.8, color = "gray40") +
  scale_fill_manual(values = palette_outcomes, name = "Outcome") +
  scale_y_continuous(labels = function(x) paste0(x, "%"),
                     expand = expansion(mult = c(0, 0.05))) +
  labs(title = "Persuasion Outcomes by AI Stance",
       subtitle = "Opposing = AI argued against participant's initial position",
       x = "AI Stance", y = "Percentage") +
  theme_thesis()

save_thesis_fig("fig_04_outcomes_by_stance.pdf", p4, width = 5, height = 4.5)

